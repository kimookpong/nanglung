"""Trace a border-connected white matte into a vector exclusion, preserving PNG bytes.

Usage: python3 scripts/trace-artwork-background.py input.png output.ts
Requires Pillow and numpy; used offline, not by the application/build.
White enclosed by the leather outline (eyes, logos, soles) stays inside the art.
"""
from collections import deque, defaultdict
from pathlib import Path
import hashlib
import sys
import numpy as np
from PIL import Image

source, output = map(Path, sys.argv[1:])
rgb = np.asarray(Image.open(source).convert("RGB"))
h, w = rgb.shape[:2]
white = rgb.min(axis=2) > 225
background = np.zeros((h, w), dtype=bool)
queue = deque()
def offer(x, y):
    if 0 <= x < w and 0 <= y < h and white[y, x] and not background[y, x]:
        background[y, x] = True
        queue.append((x, y))
for x in range(w):
    offer(x, 0); offer(x, h - 1)
for y in range(h):
    offer(0, y); offer(w - 1, y)
while queue:
    x, y = queue.popleft()
    offer(x-1, y); offer(x+1, y); offer(x, y-1); offer(x, y+1)

# Directed cell edges keep clockwise/counterclockwise contours for SVG masks.
edges = defaultdict(list)
for y, x in zip(*np.nonzero(background)):
    if y == 0 or not background[y-1, x]: edges[(x, y)].append((x+1, y))
    if x == w-1 or not background[y, x+1]: edges[(x+1, y)].append((x+1, y+1))
    if y == h-1 or not background[y+1, x]: edges[(x+1, y+1)].append((x, y+1))
    if x == 0 or not background[y, x-1]: edges[(x, y+1)].append((x, y))

def simplify(points, tolerance=0.7):
    if len(points) < 3: return points
    a, b = np.array(points[0]), np.array(points[-1])
    v = b-a
    delta = np.array(points)-a
    distance = np.abs(v[0]*delta[:, 1]-v[1]*delta[:, 0]) / max(np.linalg.norm(v), 1)
    index = int(np.argmax(distance))
    if distance[index] <= tolerance: return [points[0], points[-1]]
    return simplify(points[:index+1], tolerance)[:-1] + simplify(points[index:], tolerance)

paths = []
while edges:
    start = next(iter(edges)); points = [start]; here = start
    while True:
        next_point = edges[here].pop()
        if not edges[here]: del edges[here]
        here = next_point
        if here == start: break
        points.append(here)
    if len(points) < 4: continue
    # Split a closed loop at its farthest vertex before simplifying each arc.
    split = max(range(1, len(points)), key=lambda i:(points[i][0]-start[0])**2+(points[i][1]-start[1])**2)
    reduced = simplify(points[:split+1])[:-1] + simplify(points[split:] + [start])[:-1]
    paths.append("M" + "L".join(f"{x} {y}" for x, y in reduced) + "Z")
digest = hashlib.sha256(source.read_bytes()).hexdigest()
output.write_text(f'// Generated by scripts/trace-artwork-background.py; source SHA-256 {digest}\n'
                  f'export const THANATHORN_BACKGROUND = "{" ".join(paths)}";\n')
print(f"Traced {len(paths)} contours from {w}x{h}; {sum(len(p) for p in paths)} path characters.")
